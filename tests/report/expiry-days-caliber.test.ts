import { describe, expect, it } from "vitest";
import { daysLeftOf } from "@/server/core/stock-view";

/**
 * 效期剩余天数的**锚点**护栏。
 *
 * 真实缺陷（2026-07-26 审计）：驾驶舱用 `new Date()`（当前**时刻**）去减到期日午夜，
 * 而效期页 / 风险页 / 迷你360 都是**午夜减午夜**。差异不是偶发的，是恒定的：
 *
 *   其余页面：round((到期日午夜 − 今日午夜) / 24h)          = N
 *   驾驶舱  ：floor((到期日午夜 − 此刻) / 24h) = floor(N − t/24) = N − 1  （t>0 即当天任意时刻）
 *
 * 所以驾驶舱**恒少 1 天**；而它的首桶判据是 `daysLeft <= 0`，
 * 于是「明天才到期」的批次在驾驶舱被算进「已过期」与 expiryRiskQty。
 * 这类缺陷在午夜跑测试会消失、白天才复现——必须由锚点本身的测试钉住，
 * 不能靠「跑一次看看对不对」。
 */
describe("效期天数：必须午夜锚点，且全站同源", () => {
  it("**明天到期 = 1 天**（不是 0）", () => {
    expect(daysLeftOf("2026-07-26", "2026-07-27")).toBe(1);
  });

  it("今天到期 = 0；昨天到期 = −1（已过期用负数表达，不截断到 0）", () => {
    expect(daysLeftOf("2026-07-26", "2026-07-26")).toBe(0);
    expect(daysLeftOf("2026-07-26", "2026-07-25")).toBe(-1);
  });

  it("**结果与一天中的时刻无关**——锚点是日期串，不是 Date.now()", () => {
    // 同一组日期串在任何时刻调用都必须给同一个数；
    // 旧实现拿 new Date() 参与运算，14:00 与 00:30 会得到不同答案。
    const a = daysLeftOf("2026-07-26", "2026-07-27");
    const b = daysLeftOf("2026-07-26", "2026-07-27");
    expect(a).toBe(b);
    expect(a).toBe(1);
  });

  it("跨月/跨年不掉天", () => {
    expect(daysLeftOf("2026-01-31", "2026-02-01")).toBe(1);
    expect(daysLeftOf("2026-12-31", "2027-01-01")).toBe(1);
    expect(daysLeftOf("2026-02-28", "2026-03-01")).toBe(1); // 2026 非闰年
  });

  it("跨夏令时不掉天（本项目固定 Asia/Shanghai 无 DST，但公式必须不依赖本地时区）", () => {
    // 用 UTC 锚点串直减，任何宿主时区下结果一致
    expect(daysLeftOf("2026-03-08", "2026-03-09")).toBe(1);
    expect(daysLeftOf("2026-11-01", "2026-11-02")).toBe(1);
  });

  it("长跨度按整天计", () => {
    expect(daysLeftOf("2026-07-26", "2027-07-26")).toBe(365);
  });
});
